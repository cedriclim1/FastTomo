"""MBIR-AM-PE demo on a BF-TEM phantom with physically-grounded Bragg
corruption.

The phantom (built by `gen_mbir_phantom_data.py`) has crystalline grains
embedded in an amorphous matrix; each grain diffracts at specific tilt
angles, attenuating the rays passing through it at those tilts. This is a
faithful (if simplified) model of bright-field TEM contrast loss from
Bragg-oriented grains — much more physical than random sinogram-strip
corruption. The qualitative result expected: MBIR-AM-PE suppresses the
grain-shadow artefacts that FBP/SIRT leave behind.

Inputs (regenerated by `gen_mbir_phantom_data.py`):
    data/bftem_phantom.npy        ground-truth volume
    data/bftem_sino_clean.npy     clean forward projection (reference)
    data/bftem_sino_bragg.npy     Bragg-corrupted forward projection
    data/bftem_grains.npz         grain metadata (centres, tilt assignments)

Outputs:
    benchmarks/results/mbir_bftem_recon.png      side-by-side reconstructions
    benchmarks/results/mbir_bftem_metrics.txt    RMSE vs ground-truth volume

Run:
    python benchmarks/scripts/gen_mbir_phantom_data.py   # one-time
    python benchmarks/scripts/run_mbir_bftem_demo.py
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import torch
import matplotlib.pyplot as plt

import fasttomo as ft


def reconstruct_fbp(sino, angles, Nz):
    return ft.run_fbp(sino, angles, Nz=Nz, positivity=True).cpu()


def reconstruct_sirt(sino, angles, Nz, n_iter=50):
    return ft.run_sirt(sino, angles, n_iter=n_iter, Nz=Nz, positivity=True).cpu()


def reconstruct_mbir(sino, angles, Nz, *, huber_T, label, sigma_f=0.1,
                     sigma_init=0.5, outer_iters=100):
    """MBIR with fixed σ (auto-tune is unstable under sharp Bragg extinction —
    the σ closed-form runs away to ~0 when most pixels read as anomalies,
    which then makes the rest read as anomalies too. Documented as a
    known limitation; set `estimate_variance=False` and pick σ manually
    for synthetic phantoms with high-magnitude anomalies)."""
    print(f"  running MBIR ({label}) ...")
    vol = ft.run_mbir(
        sino, angles, Nz=Nz,
        sigma_f=sigma_f,
        huber_T=huber_T, huber_delta=0.5,
        estimate_offset=False,
        estimate_variance=False,
        sigma_init=sigma_init,
        outer_iters=outer_iters,
        multires_levels=1,
        seed=0,
    )
    return vol.cpu()


def grain_slice_index(grain_centers: np.ndarray) -> int:
    """Pick a Y index that maximises the number of grains touched by the
    slice (i.e. where the most grain spheres intersect the plane). Falls
    back to the median Y of the grain centres."""
    if len(grain_centers) == 0:
        return 100
    # Each grain center is (y, z, x); choose the Y with most centers near it.
    ys = grain_centers[:, 0]
    return int(np.median(ys))


def xz_slice(vol, iy: int) -> np.ndarray:
    """XZ slice at Y=iy."""
    return vol[iy].numpy() if hasattr(vol, "numpy") else vol[iy]


def rmse(a, b):
    return float(np.sqrt(np.mean((a - b) ** 2)))


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--data-dir", type=Path, default=Path("data"))
    parser.add_argument("--device", type=str, default="cuda:0")
    parser.add_argument("--out-fig", type=Path,
                        default=Path("benchmarks/results/mbir_bftem_recon.png"))
    parser.add_argument("--out-metrics", type=Path,
                        default=Path("benchmarks/results/mbir_bftem_metrics.txt"))
    parser.add_argument("--mbir-iters", type=int, default=100)
    args = parser.parse_args(argv)

    args.out_fig.parent.mkdir(parents=True, exist_ok=True)
    device = torch.device(args.device if torch.cuda.is_available() else "cpu")

    # Load artifacts from the generator script.
    phantom    = np.load(args.data_dir / "bftem_phantom.npy").astype(np.float32)
    clean_sino = np.load(args.data_dir / "bftem_sino_clean.npy").astype(np.float32)
    bragg_sino = np.load(args.data_dir / "bftem_sino_bragg.npy").astype(np.float32)
    grain_meta = np.load(args.data_dir / "bftem_grains.npz")

    print(f"phantom:  shape={phantom.shape}, intensity range [{phantom.min():.3f}, {phantom.max():.3f}]")
    print(f"  {len(grain_meta['centers'])} grains, bragg_factor={float(grain_meta['bragg_factor']):.3f}")
    print(f"clean sino: max={clean_sino.max():.2f}")
    print(f"bragg sino: min={bragg_sino.min():.4f} (Bragg extinction)")

    sino_clean = torch.from_numpy(clean_sino).to(device)
    sino_corrupt = torch.from_numpy(bragg_sino).to(device)
    angles = torch.from_numpy(grain_meta["angles_deg"].astype(np.float32)).to(device)
    Nz = phantom.shape[1]

    print("FBP (Bragg):")
    fbp_vol = reconstruct_fbp(sino_corrupt, angles, Nz)
    print("SIRT (Bragg):")
    sirt_vol = reconstruct_sirt(sino_corrupt, angles, Nz)
    print("MBIR conventional (Bragg, T=inf):")
    mbir_conv = reconstruct_mbir(
        sino_corrupt, angles, Nz,
        huber_T=float("inf"), label="conventional", outer_iters=args.mbir_iters,
    )
    print("MBIR-AM (Bragg, T=2, delta=0.5):")
    mbir_am = reconstruct_mbir(
        sino_corrupt, angles, Nz,
        huber_T=2.0, label="MBIR-AM", outer_iters=args.mbir_iters,
    )

    # Metrics against the ground-truth volume (this is real: we built the
    # phantom, so we can compare reconstructions directly to it).
    metrics = {
        "FBP":              rmse(fbp_vol.numpy(),   phantom),
        "SIRT":             rmse(sirt_vol.numpy(),  phantom),
        "MBIR conventional":rmse(mbir_conv.numpy(), phantom),
        "MBIR-AM":       rmse(mbir_am.numpy(),   phantom),
    }
    print("\nRMSE vs ground-truth phantom:")
    for k, v in metrics.items():
        print(f"  {k:<22s} {v:.6f}")
    with open(args.out_metrics, "w") as f:
        f.write("RMSE vs ground-truth BF-TEM phantom (with Bragg-grain corruption)\n")
        f.write("=" * 65 + "\n")
        for k, v in metrics.items():
            f.write(f"{k:<22s} {v:.6f}\n")

    # Pick a Y slice that actually contains grains so the Bragg shadows
    # show up — central XZ is matrix-only on most realisations.
    iy_show = grain_slice_index(grain_meta["centers"])
    n_intersect = (np.abs(grain_meta["centers"][:, 0] - iy_show) <= grain_meta["radii"]).sum()
    print(f"\nVisualising Y={iy_show} (intersects {n_intersect} grains)")
    panels = [
        ("Ground truth",        xz_slice(phantom,   iy_show)),
        ("FBP (Bragg)",         xz_slice(fbp_vol,   iy_show)),
        ("SIRT (Bragg)",        xz_slice(sirt_vol,  iy_show)),
        ("MBIR conv. (Bragg)",  xz_slice(mbir_conv, iy_show)),
        ("MBIR-AM (Bragg)",     xz_slice(mbir_am,   iy_show)),
    ]
    vmin = min(p[1].min() for p in panels)
    vmax = max(p[1].max() for p in panels)
    fig, axes = plt.subplots(1, len(panels), figsize=(3 * len(panels), 3))
    for ax, (title, img) in zip(axes, panels):
        ax.imshow(img, cmap="gray", vmin=vmin, vmax=vmax)
        ax.set_title(title, fontsize=9)
        ax.axis("off")
    fig.suptitle(
        "MBIR-AM suppresses Bragg-shadow streaks from crystalline grains",
        fontsize=11,
    )
    fig.tight_layout()
    fig.savefig(args.out_fig, dpi=120, bbox_inches="tight")
    print(f"\nFigure → {args.out_fig}")
    print(f"Metrics → {args.out_metrics}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
