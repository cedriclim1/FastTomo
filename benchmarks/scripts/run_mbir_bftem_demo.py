"""MBIR-AM-PE demo on the Bragg-corrupted QuantEM phantom sinogram.

Reconstructs the same Bragg-corrupted BF-TEM phantom with four algorithms
side-by-side and saves a comparison figure + RMSE table. The qualitative
result expected: MBIR-AM-PE suppresses the streaks that FBP/SIRT leave
behind. Mirrors Fig. 5 of Venkatakrishnan et al. 2015 at a smaller scale.

Inputs (pre-generated by benchmarks/scripts/gen_mbir_phantom_data.py):
    data/quantem_phantom_perfect_sino.npy        clean sinogram
    data/quantem_phantom_perfect_sino_bftem.npy  Bragg-corrupted sinogram

Outputs:
    benchmarks/results/mbir_bftem_recon.png      side-by-side panels
    benchmarks/results/mbir_bftem_metrics.txt    RMSE comparison

Usage:
    python benchmarks/scripts/run_mbir_bftem_demo.py
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import torch
import matplotlib.pyplot as plt

import fasttomo as ft


def angles_for_sino(n_angles: int) -> torch.Tensor:
    """The QuantEM perfect sinogram covers ±70° in 29 tilts (matches
    the project's canonical phantom — see benchmarks/make_perfect_sino.py)."""
    return torch.linspace(-70.0, 70.0, n_angles)


def reconstruct_fbp(sino: torch.Tensor, angles: torch.Tensor, Nz: int) -> torch.Tensor:
    return ft.run_fbp(sino, angles, Nz=Nz, positivity=True, mask=False).cpu()


def reconstruct_sirt(sino: torch.Tensor, angles: torch.Tensor, Nz: int, n_iter: int = 50) -> torch.Tensor:
    return ft.run_sirt(sino, angles, n_iter=n_iter, Nz=Nz, positivity=True, mask=False).cpu()


def reconstruct_mbir(
    sino: torch.Tensor,
    angles: torch.Tensor,
    Nz: int,
    *,
    huber_T: float,
    label: str,
    sigma_f: float = 0.5,
    outer_iters: int = 100,
) -> torch.Tensor:
    """One MBIR variant. `huber_T = inf` → conventional MBIR (no anomaly
    handling); `huber_T = 3, δ = 0.5` → MBIR-AM-PE (the paper's recipe)."""
    print(f"  running MBIR ({label}) ...")
    vol = ft.run_mbir(
        sino, angles,
        Nz=Nz,
        sigma_f=sigma_f,
        huber_T=huber_T, huber_delta=0.5,
        estimate_offset=False,      # the BF-TEM offset stays at zero for the QuantEM phantom
        estimate_variance=True,
        outer_iters=outer_iters,
        multires_levels=1,
        seed=0,
    )
    return vol.cpu()


def central_slice(vol: torch.Tensor) -> np.ndarray:
    """Central XZ slice of a [Ny, Nz, Nx] volume."""
    iy = vol.shape[0] // 2
    return vol[iy].numpy()


def rmse(a: np.ndarray, b: np.ndarray) -> float:
    return float(np.sqrt(np.mean((a - b) ** 2)))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--clean-sino",
                        type=Path,
                        default=Path("data/quantem_phantom_perfect_sino.npy"))
    parser.add_argument("--bragg-sino",
                        type=Path,
                        default=Path("data/quantem_phantom_perfect_sino_bftem.npy"))
    parser.add_argument("--device", type=str, default="cuda:0")
    parser.add_argument("--out-fig",
                        type=Path,
                        default=Path("benchmarks/results/mbir_bftem_recon.png"))
    parser.add_argument("--out-metrics",
                        type=Path,
                        default=Path("benchmarks/results/mbir_bftem_metrics.txt"))
    parser.add_argument("--mbir-iters", type=int, default=100)
    args = parser.parse_args(argv)

    args.out_fig.parent.mkdir(parents=True, exist_ok=True)

    device = torch.device(args.device if torch.cuda.is_available() else "cpu")

    clean = np.load(args.clean_sino).astype(np.float32)
    corrupt = np.load(args.bragg_sino).astype(np.float32)
    print(f"clean sino:   shape={clean.shape}  max={clean.max():.3f}")
    print(f"bragg sino:   shape={corrupt.shape}  max={corrupt.max():.3f}")

    sino_clean = torch.from_numpy(clean).to(device)
    sino_corrupt = torch.from_numpy(corrupt).to(device)
    n_angles = clean.shape[0]
    angles = angles_for_sino(n_angles).to(device)
    Nz = clean.shape[2]

    # Run baselines on the Bragg-corrupted sinogram.
    print("FBP:")
    fbp_vol = reconstruct_fbp(sino_corrupt, angles, Nz)
    print("SIRT:")
    sirt_vol = reconstruct_sirt(sino_corrupt, angles, Nz)
    print("MBIR (conventional, T=inf):")
    mbir_conv = reconstruct_mbir(
        sino_corrupt, angles, Nz,
        huber_T=float("inf"), label="conventional",
        outer_iters=args.mbir_iters,
    )
    print("MBIR-AM-PE (T=3, delta=0.5):")
    mbir_am = reconstruct_mbir(
        sino_corrupt, angles, Nz,
        huber_T=3.0, label="MBIR-AM-PE",
        outer_iters=args.mbir_iters,
    )

    # Reference: same MBIR-AM-PE run on the CLEAN sinogram for "best possible"
    # benchmark — what reconstructions look like without any Bragg corruption.
    print("MBIR (clean reference):")
    ref = reconstruct_mbir(
        sino_clean, angles, Nz,
        huber_T=float("inf"), label="reference (clean)",
        outer_iters=args.mbir_iters,
    )

    # Compute RMSE vs the clean-data MBIR reference (no ground-truth volume
    # is shipped with the artifact, so we use the clean-data recon as the
    # comparator — mirrors held-out-projection CV in spirit).
    ref_np = ref.numpy()
    metrics = {
        "FBP":              rmse(fbp_vol.numpy(),  ref_np),
        "SIRT":             rmse(sirt_vol.numpy(), ref_np),
        "MBIR conventional":rmse(mbir_conv.numpy(), ref_np),
        "MBIR-AM-PE":       rmse(mbir_am.numpy(),   ref_np),
    }
    print("\nRMSE vs clean-data reference reconstruction:")
    for k, v in metrics.items():
        print(f"  {k:<22s} {v:.6f}")
    with open(args.out_metrics, "w") as f:
        f.write("RMSE vs clean-data MBIR reference reconstruction\n")
        f.write("=" * 60 + "\n")
        for k, v in metrics.items():
            f.write(f"{k:<22s} {v:.6f}\n")

    # Side-by-side central-slice figure.
    panels = [
        ("Reference (clean → MBIR)", central_slice(ref)),
        ("FBP (Bragg)",              central_slice(fbp_vol)),
        ("SIRT (Bragg)",             central_slice(sirt_vol)),
        ("MBIR conv. (Bragg)",       central_slice(mbir_conv)),
        ("MBIR-AM-PE (Bragg)",       central_slice(mbir_am)),
    ]
    vmin = min(p[1].min() for p in panels)
    vmax = max(p[1].max() for p in panels)
    fig, axes = plt.subplots(1, len(panels), figsize=(3 * len(panels), 3))
    for ax, (title, img) in zip(axes, panels):
        ax.imshow(img, cmap="gray", vmin=vmin, vmax=vmax)
        ax.set_title(title, fontsize=9)
        ax.axis("off")
    fig.suptitle(
        "MBIR-AM-PE reconstruction on Bragg-corrupted QuantEM phantom",
        fontsize=11,
    )
    fig.tight_layout()
    fig.savefig(args.out_fig, dpi=120, bbox_inches="tight")
    print(f"\nFigure → {args.out_fig}")
    print(f"Metrics → {args.out_metrics}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
