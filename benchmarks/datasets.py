"""Dataset loaders for benchmarks.

Two data sources:

* ``load_phantom_tilt_series``: the quantem-tutorials phantom + sinogram with a
  1° tilt-axis error baked in (lives outside the repo at
  /home/cedlim/quantem/quantem-tutorials/data/).  Use for pose-optimization
  benchmarks.

* ``load_fair_tilt_series``: the in-repo FePt phantom
  (``data/fept_phantom_200.npy``) paired with a perfect sinogram generated by
  ``scripts/make_perfect_sino.py`` (``data/fept_phantom_200_perfect_sino.npy``).
  Zero pose/shift error — use for fair algorithm quality comparisons.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import torch

DEFAULT_DATA_DIR = Path("/home/cedlim/quantem/quantem-tutorials/data")
REPO_DATA_DIR = Path(__file__).resolve().parent.parent / "data"


def load_phantom_tilt_series(
    device: torch.device | str = "cuda",
    data_dir: Path | str = DEFAULT_DATA_DIR,
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    """Load the (phantom, sinogram, angles_deg) triple as float32 tensors.

    Applies the per-projection ``np.rot90`` alignment from
    ``Notebooks/opt_test.ipynb`` so the tilt axis lines up with FastTomo's Y.

    Returns
    -------
    phantom : [200, 200, 200] float32
    sinogram : [29, 200, 200] float32 — [n_angles, Ny, N_det]
    angles_deg : [29] float32 — −70°…70° step 5°
    """
    data_dir = Path(data_dir)
    phantom_np = np.load(data_dir / "phantom.npy").astype(np.float32)
    ts_np = np.load(data_dir / "tilt_series_1_deg_tilt_axis.npy").astype(np.float32)
    ang_np = np.load(data_dir / "tilt_angles_1_deg_tilt_axis.npy").astype(np.float32)

    # Reorient phantom from quantem axes to FastTomo's [Ny, Nz, Nx].
    # The per-projection np.rot90 below + the .transpose(2, 0, 1) leave the
    # phantom's tilt axis pointing opposite to what every reconstruction method
    # produces from the rot90'd sinogram (verified across SIRT/RESIRE/GENFIRE/
    # ASTRA/TorchRadon — every recon needed flip(0) to align). Flip the
    # phantom here once so SSIM/NMSE are computed against the matching
    # orientation across all methods.
    phantom_np = phantom_np.transpose(2, 0, 1)[::-1].copy()
    ts_np = np.stack([np.rot90(img) for img in ts_np])

    phantom = torch.from_numpy(phantom_np).to(device)
    sinogram = torch.from_numpy(ts_np).to(device)
    angles = torch.from_numpy(ang_np).to(device)
    return phantom, sinogram, angles


def load_fair_tilt_series(
    device: torch.device | str = "cuda",
    quantem_data_dir: Path | str = DEFAULT_DATA_DIR,
    repo_data_dir: Path | str = REPO_DATA_DIR,
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    """Load the quantem phantom + perfect (zero-error) sinogram as float32 tensors.

    Uses the same ``phantom.npy`` and axis reorientation as
    ``load_phantom_tilt_series``, but pairs it with a sinogram generated by
    ``scripts/make_perfect_sino.py`` (zero pose/shift error) instead of the
    1°-tilt-axis-error sinogram.

    Run ``python scripts/make_perfect_sino.py`` once to create
    ``data/quantem_phantom_perfect_sino.npy`` before calling this loader.

    Returns
    -------
    phantom  : [200, 200, 200] float32  — ground-truth volume (reoriented)
    sinogram : [29, 200, 200]  float32  — perfect projections, [n_angles, Ny, N_det]
    angles   : [29]            float32  — −70°…+70°, 5° step
    """
    phantom_np = np.load(Path(quantem_data_dir) / "phantom.npy").astype(np.float32)
    phantom_np = phantom_np.transpose(2, 0, 1)[::-1].copy()
    phantom = torch.from_numpy(phantom_np).to(device)
    sinogram = torch.from_numpy(
        np.load(Path(repo_data_dir) / "quantem_phantom_perfect_sino.npy").astype(np.float32)
    ).to(device)
    angles = torch.linspace(-70.0, 70.0, 29, device=device)
    return phantom, sinogram, angles
